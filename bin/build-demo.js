#!/usr/bin/env node

const { execSync } = require("child_process");
const versions = require("../projects/demo-showcase/src/versions.json");
const { exit } = require("process");
const fs = require("fs");
const path = require("path");

function printHelp() {
  console.log(`
Usage: build-demo.js [version]

Builds the demo-showcase application and flattens the output directory
to remove the "browser" folder generated by the application builder.

Arguments:
  [version]    Optional. The version to build (e.g., v1, v2).
               If not provided, it defaults to the 'latest' from versions.json.
               Use 'root' to build without a version suffix (into the docs root).

Options:
  --help, -h   Show this help message.
`);
}

/**
 * Cleans the target directory before building.
 * Preserves version directories when cleaning the root.
 * @param {String} outPath
 * @param {Boolean} isRoot
 */
function cleanTargetDirectory(outPath, isRoot) {
  if (!fs.existsSync(outPath)) return;

  console.log(`Cleaning target directory: ${outPath}`);
  const knownVersions = Array.isArray(versions.versions)
    ? versions.versions.map(({ name }) => name) // Extract only the name from the versions array
    : [];

  const items = fs.readdirSync(outPath);
  for (const item of items) {
    if (isRoot && knownVersions.includes(item)) {
      continue;
    }

    const itemPath = path.join(outPath, item);
    fs.rmSync(itemPath, { recursive: true, force: true });
  }
}

/**
 * Builds the demo app for a specific version.
 * @param {String} version
 * @returns {String} The output path where the build was generated
 */
function buildVersion(version) {
  const isRoot = version === "root" || !version;
  const suffixed = isRoot ? "" : `${version}/`;
  const outPath = isRoot ? `docs` : `docs/${version}`;
  const baseHref = `/ngx-mol-viewers/${suffixed}`;

  cleanTargetDirectory(outPath, isRoot);

  const command = `ng build -c=production --output-path ${outPath} --base-href ${baseHref} demo-showcase`;

  try {
    console.log(`Running \n${command}`);
    execSync(command, { stdio: "inherit" });
  } catch (error) {
    console.error(`Error occured while running command: ${command}`);
    console.error(error.toString());
    exit(1);
  }

  return outPath;
}

/**
 * Recursively moves files from src to dest.
 * @param {String} src
 * @param {String} dest
 */
function moveFilesRecursive(src, dest) {
  if (!fs.existsSync(dest)) {
    fs.mkdirSync(dest, { recursive: true });
  }

  const items = fs.readdirSync(src);
  for (const item of items) {
    const srcPath = path.join(src, item);
    const destPath = path.join(dest, item);

    if (fs.statSync(srcPath).isDirectory()) {
      moveFilesRecursive(srcPath, destPath);
    } else {
      fs.renameSync(srcPath, destPath);
    }
  }
}

/**
 * Flattens the browser directory created by the Angular builder.
 * Uses recursive renaming (moving) to avoid heavy disk I/O from copying.
 * @param {String} outPath
 */
function flattenOutput(outPath) {
  const browserDir = path.join(process.cwd(), outPath, "browser");
  if (!fs.existsSync(browserDir)) {
    console.warn(`browser dir not found in ${outPath}`);
    return;
  }

  console.log(
    `Flattening output: moving files from ${browserDir} to ${outPath}`,
  );
  const destDir = path.join(process.cwd(), outPath);

  moveFilesRecursive(browserDir, destDir);

  // Remove the now-empty browser directory hierarchy
  fs.rmSync(browserDir, { recursive: true, force: true });
}

function main() {
  const args = process.argv.slice(2);

  if (args.includes("--help") || args.includes("-h")) {
    printHelp();
    exit(0);
  }

  const targetVersion = args.length > 0 ? args[0] : "root";

  console.log(`Starting build for version: ${targetVersion}`);
  const outPath = buildVersion(targetVersion);
  flattenOutput(outPath);
}

if (require.main === module) {
  main();
}
